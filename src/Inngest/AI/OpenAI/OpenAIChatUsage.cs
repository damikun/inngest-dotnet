using System.Text.Json;
using System.Text.Json.Serialization;

namespace Inngest;

/// <summary>The tokens an OpenAI chat completion used.</summary>
public sealed record OpenAIChatUsage
{
    [JsonPropertyName("prompt_tokens")]
    public int PromptTokens { get; init; }

    [JsonPropertyName("completion_tokens")]
    public int CompletionTokens { get; init; }

    [JsonPropertyName("total_tokens")]
    public int TotalTokens { get; init; }

    [JsonPropertyName("prompt_tokens_details")]
    public OpenAIInputTokensDetails? PromptTokensDetails { get; init; }

    [JsonPropertyName("completion_tokens_details")]
    public OpenAIOutputTokensDetails? CompletionTokensDetails { get; init; }

    /// <summary>Properties this record does not have, sent and read as they are.</summary>
    [JsonExtensionData]
    public IDictionary<string, JsonElement>? AdditionalProperties { get; set; }
}
