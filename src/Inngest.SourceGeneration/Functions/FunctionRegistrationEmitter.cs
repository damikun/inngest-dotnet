using System.Text;

namespace Inngest.SourceGeneration.Functions;

internal static class FunctionRegistrationEmitter
{
    public const string HintName = "Inngest.FunctionRegistration.g.cs";

    public static string Emit(Registration registration, string generatorVersion)
    {
        var options = registration.Options;
        var accessibility = options.IsPublic ? "public" : "internal";
        var builder = new StringBuilder();

        builder.Append("// <auto-generated/>\n");
        builder.Append("#nullable enable\n");
        builder.Append('\n');
        builder.Append("namespace Inngest\n");
        builder.Append("{\n");
        builder.Append("    /// <summary>Registers the function classes of this assembly.</summary>\n");
        builder.Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"Inngest.SourceGeneration\", \"").Append(generatorVersion).Append("\")]\n");
        builder.Append("    ").Append(accessibility).Append(" static class ").Append(ClassName(registration.AssemblyName)).Append('\n');
        builder.Append("    {\n");
        builder.Append("        /// <summary>\n");
        builder.Append("        /// Registers every class of this assembly that has [InngestFunction] and derives from InngestFunction, each with the\n");
        builder.Append("        /// options its attributes give, as AddFunction&lt;TFunction&gt;() does.\n");
        builder.Append("        /// </summary>\n");
        builder.Append("        ").Append(accessibility).Append(" static global::Inngest.IInngestBuilder ").Append(options.MethodName)
            .Append("(this global::Inngest.IInngestBuilder builder)\n");
        builder.Append("        {\n");
        builder.Append("            global::System.ArgumentNullException.ThrowIfNull(builder);\n");
        builder.Append('\n');

        // One statement for each class. A chain of calls is one expression, and the compiler gives up on a long one.
        foreach (var typeName in registration.TypeNames)
        {
            builder.Append("            global::Inngest.InngestBuilderExtensions.AddFunction<").Append(typeName).Append(">(builder);\n");
        }

        builder.Append('\n');
        builder.Append("            return builder;\n");
        builder.Append("        }\n");
        builder.Append("    }\n");
        builder.Append("}\n");
        return builder.ToString();
    }

    // Named after the assembly: a public class of the same name in two assemblies of one app would hide the extension methods
    // of the one that is referenced, and the compiler only warns about it.
    private static string ClassName(string assemblyName)
    {
        var name = new StringBuilder("InngestFunctionRegistration_");
        foreach (var character in assemblyName)
        {
            name.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return name.ToString();
    }
}
