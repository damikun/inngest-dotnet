        var test = new GeneratorTest(source, properties: "build_property.InngestGenerateFunctionRegistration = yes\n", enabled: false);
        test.TestState.ExpectedDiagnostics.Add(new DiagnosticResult(DiagnosticIds.InvalidOption, DiagnosticSeverity.Warning)
