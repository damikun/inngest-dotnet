    [Fact]
    public async Task Registers_each_function_class_by_calling_AddFunction()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using Inngest;

            namespace Shop.Orders
            {
                public sealed record OrderPlaced(string Id);

                [InngestFunction("order-placed")]
                [EventTrigger("shop/order.placed")]
                public sealed class OnOrderPlaced : InngestFunction<OrderPlaced>
                {
                    public override Task<object?> ExecuteAsync(FunctionContext<OrderPlaced> context, CancellationToken cancellationToken) =>
                        Task.FromResult<object?>(null);
                }
            }
            """;

        // In full, once: the other tests build this text with Snapshot.Registration.
        const string generated = """
            // <auto-generated/>
            #nullable enable
            #pragma warning disable CS0612, CS0618

            namespace Inngest
            {
                /// <summary>Registers the function classes of this assembly.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("Inngest.SourceGeneration", "{version}")]
                internal static class InngestFunctionRegistration_TestProject
                {
                    /// <summary>
                    /// Registers every class of this assembly that has [InngestFunction] and derives from InngestFunction, each with the
                    /// options its attributes give, as AddFunction&lt;TFunction&gt;() does.
                    /// </summary>
                    internal static global::Inngest.IInngestBuilder AddInngestFunctions(this global::Inngest.IInngestBuilder builder)
                    {
                        global::System.ArgumentNullException.ThrowIfNull(builder);

                        global::Inngest.InngestBuilderExtensions.AddFunction<global::Shop.Orders.OnOrderPlaced>(builder);

                        return builder;
                    }
                }
            }

            """;

        await new GeneratorTest(source, generated).RunAsync();
    }

