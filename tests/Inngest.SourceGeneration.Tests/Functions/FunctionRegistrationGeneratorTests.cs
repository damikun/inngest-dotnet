    [Fact]
    public void Names_that_differ_only_in_punctuation_get_different_classes()
    {
        string[] assemblies = ["My-Lib", "My.Lib", "My_Lib", "My Lib", "MyLib"];

        var names = assemblies.Select(FunctionRegistrationEmitter.ClassName).ToList();

        names.Distinct(StringComparer.Ordinal).Count().ShouldBe(assemblies.Length);
        names.ShouldAllBe(name => name.StartsWith("InngestFunctionRegistration_My", StringComparison.Ordinal));
        names.ShouldAllBe(name => name.All(character => char.IsLetterOrDigit(character) || character == '_'));

        // The same name always gives the same class, in every build.
        FunctionRegistrationEmitter.ClassName("My-Lib").ShouldBe(names[0]);
    }

