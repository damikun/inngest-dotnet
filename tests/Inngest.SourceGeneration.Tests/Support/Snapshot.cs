using Inngest.SourceGeneration.Functions;

namespace Inngest.SourceGeneration.Tests.Support;

// The file the generator writes, for a list of classes. FunctionRegistrationGeneratorTests.Registers_each_function_class...
// holds the same text in full; this keeps the other tests to what they are about, which classes are in it.
internal static class Snapshot
{
    public static string Registration(string assembly, string[] typeNames, string method = "AddInngestFunctions", string accessibility = "internal")
    {
        var calls = string.Join("\n", typeNames.Select(static typeName => $"            global::Inngest.InngestBuilderExtensions.AddFunction<{typeName}>(builder);"));

        return $$"""
            // <auto-generated/>
            #nullable enable
            #pragma warning disable CS0612, CS0618

            namespace Inngest
            {
                /// <summary>Registers the function classes of this assembly.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("Inngest.SourceGeneration", "{version}")]
                {{accessibility}} static class {{FunctionRegistrationEmitter.ClassName(assembly)}}
                {
                    /// <summary>
                    /// Registers every class of this assembly that has [InngestFunction] and derives from InngestFunction, each with the
                    /// options its attributes give, as AddFunction&lt;TFunction&gt;() does.
                    /// </summary>
                    {{accessibility}} static global::Inngest.IInngestBuilder {{method}}(this global::Inngest.IInngestBuilder builder)
                    {
                        global::System.ArgumentNullException.ThrowIfNull(builder);

            {{calls}}

                        return builder;
                    }
                }
            }

            """;
    }
}
